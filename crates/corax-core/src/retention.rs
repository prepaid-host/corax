//! State retention in Nagios 3 `retention.dat` format.
//!
//! Using the Nagios format means a site can switch between Nagios and corax in both
//! directions without losing states, acknowledgements, comments or downtimes.
//! corax writes a few additional keys (`x_corax_*`); Nagios ignores unknown keys.

use std::fmt::Write as _;
use std::path::Path;

use crate::checkresult::{escape_newlines, unescape_newlines};
use crate::model::*;
use crate::World;

fn b(v: bool) -> u8 {
    v as u8
}

fn write_state(out: &mut String, st: &CheckState, is_host: bool) {
    let _ = writeln!(out, "modified_attributes={}", st.modified_attributes);
    let _ = writeln!(out, "has_been_checked={}", b(st.has_been_checked));
    let _ = writeln!(out, "check_execution_time={:.3}", st.execution_time);
    let _ = writeln!(out, "check_latency={:.3}", st.latency);
    let _ = writeln!(out, "check_type={}", st.check_type as u8);
    let _ = writeln!(out, "current_state={}", st.current_state);
    let _ = writeln!(out, "last_state={}", st.last_state);
    let _ = writeln!(out, "last_hard_state={}", st.last_hard_state);
    let _ = writeln!(out, "last_event_id={}", st.last_event_id);
    let _ = writeln!(out, "current_event_id={}", st.current_event_id);
    let _ = writeln!(out, "current_problem_id={}", st.current_problem_id);
    let _ = writeln!(out, "last_problem_id={}", st.last_problem_id);
    let _ = writeln!(out, "plugin_output={}", escape_newlines(&st.plugin_output));
    let _ = writeln!(out, "long_plugin_output={}", escape_newlines(&st.long_plugin_output));
    let _ = writeln!(out, "performance_data={}", escape_newlines(&st.perf_data));
    let _ = writeln!(out, "last_check={}", st.last_check);
    let _ = writeln!(out, "next_check={}", st.next_check);
    let _ = writeln!(out, "check_options=0");
    let _ = writeln!(out, "current_attempt={}", st.current_attempt);
    let _ = writeln!(out, "state_type={}", st.state_type as u8);
    let _ = writeln!(out, "last_state_change={}", st.last_state_change);
    let _ = writeln!(out, "last_hard_state_change={}", st.last_hard_state_change);
    let names: &[&str] = if is_host {
        &["last_time_up", "last_time_down", "last_time_unreachable"]
    } else {
        &["last_time_ok", "last_time_warning", "last_time_critical", "last_time_unknown"]
    };
    for (i, n) in names.iter().enumerate() {
        let _ = writeln!(out, "{n}={}", st.last_time_in_state[i]);
    }
    let _ = writeln!(out, "last_notification={}", st.last_notification);
    let _ = writeln!(out, "current_notification_number={}", st.current_notification_number);
    let _ = writeln!(out, "notifications_enabled={}", b(st.notifications_enabled));
    let _ = writeln!(out, "problem_has_been_acknowledged={}", b(st.acknowledged));
    let _ = writeln!(out, "acknowledgement_type={}", st.acknowledgement_type);
    let _ = writeln!(out, "active_checks_enabled={}", b(st.active_checks_enabled));
    let _ = writeln!(out, "passive_checks_enabled={}", b(st.passive_checks_enabled));
    let _ = writeln!(out, "event_handler_enabled={}", b(st.event_handler_enabled));
    let _ = writeln!(out, "flap_detection_enabled={}", b(st.flap_detection_enabled));
    let _ = writeln!(out, "failure_prediction_enabled=1");
    let _ = writeln!(out, "process_performance_data={}", b(st.process_performance_data));
    let _ = writeln!(out, "{}={}", if is_host { "obsess_over_host" } else { "obsess_over_service" }, b(st.obsess));
    let _ = writeln!(out, "is_flapping={}", b(st.is_flapping));
    let _ = writeln!(out, "percent_state_change={:.2}", st.percent_state_change);
    let hist: Vec<String> = (0..st.state_history_len.min(FLAP_HISTORY))
        .map(|i| {
            st.state_history[(st.state_history_index + FLAP_HISTORY - st.state_history_len + i) % FLAP_HISTORY]
                .to_string()
        })
        .collect();
    let _ = writeln!(out, "state_history={}", hist.join(","));
    let _ = writeln!(out, "x_corax_next_notification={}", st.next_notification);
    let _ = writeln!(out, "x_corax_ack_expire={}", st.acknowledgement_expire_time);
    let _ = writeln!(out, "x_corax_no_more_notifications={}", b(st.no_more_notifications));
}

/// Serialize the complete retention state.
pub fn serialize(w: &World, now: i64) -> String {
    let mut out = String::with_capacity(1024 + (w.hosts.len() + w.services.len()) * 1200);
    out.push_str("########################################\n#      NAGIOS STATE RETENTION FILE\n#\n# THIS FILE IS AUTOMATICALLY GENERATED\n# BY CORAX.  DO NOT MODIFY THIS FILE!\n########################################\n");
    let _ = writeln!(out, "info {{\ncreated={now}\nversion=3.5.1\nlast_update_check=0\nupdate_available=0\nupdate_uid=0\nlast_version=\nnew_version=\n}}");
    let p = &w.program;
    let _ = writeln!(
        out,
        "program {{\nmodified_host_attributes={}\nmodified_service_attributes={}\nenable_notifications={}\nactive_service_checks_enabled={}\npassive_service_checks_enabled={}\nactive_host_checks_enabled={}\npassive_host_checks_enabled={}\nenable_event_handlers={}\nobsess_over_services={}\nobsess_over_hosts={}\ncheck_service_freshness={}\ncheck_host_freshness={}\nenable_flap_detection={}\nenable_failure_prediction=1\nprocess_performance_data={}\nglobal_host_event_handler=\nglobal_service_event_handler=\nnext_comment_id={}\nnext_downtime_id={}\nnext_event_id={}\nnext_problem_id={}\nnext_notification_id={}\n}}",
        p.modified_host_attributes,
        p.modified_service_attributes,
        b(p.enable_notifications),
        b(p.execute_service_checks),
        b(p.accept_passive_service_checks),
        b(p.execute_host_checks),
        b(p.accept_passive_host_checks),
        b(p.enable_event_handlers),
        b(p.obsess_over_services),
        b(p.obsess_over_hosts),
        b(p.check_service_freshness),
        b(p.check_host_freshness),
        b(p.enable_flap_detection),
        b(p.process_performance_data),
        p.next_comment_id,
        p.next_downtime_id,
        p.next_event_id,
        p.next_problem_id,
        p.next_notification_id,
    );
    for h in &w.hosts {
        let _ = writeln!(out, "host {{\nhost_name={}", h.cfg.name);
        write_state(&mut out, &h.st, true);
        out.push_str("}\n");
    }
    for s in &w.services {
        let _ = writeln!(
            out,
            "service {{\nhost_name={}\nservice_description={}",
            w.host(s.host).cfg.name,
            s.cfg.description
        );
        write_state(&mut out, &s.st, false);
        out.push_str("}\n");
    }
    for c in &w.contacts {
        let _ = writeln!(
            out,
            "contact {{\ncontact_name={}\nmodified_attributes={}\nmodified_host_attributes=0\nmodified_service_attributes=0\nlast_host_notification={}\nlast_service_notification={}\nhost_notifications_enabled={}\nservice_notifications_enabled={}\n}}",
            c.cfg.name,
            c.modified_attributes,
            c.last_host_notification,
            c.last_service_notification,
            b(c.host_notifications_enabled),
            b(c.service_notifications_enabled)
        );
    }
    for c in w.comments.values() {
        let (kind, ident) = match c.target {
            Target::Host(h) => ("hostcomment", format!("host_name={}", w.host(h).cfg.name)),
            Target::Service(s) => {
                let svc = w.service(s);
                (
                    "servicecomment",
                    format!("host_name={}\nservice_description={}", w.host(svc.host).cfg.name, svc.cfg.description),
                )
            }
        };
        let _ = writeln!(
            out,
            "{kind} {{\n{ident}\nentry_type={}\ncomment_id={}\nsource={}\npersistent={}\nentry_time={}\nexpires={}\nexpire_time={}\nauthor={}\ncomment_data={}\n}}",
            c.entry_type,
            c.id,
            c.source,
            b(c.persistent),
            c.entry_time,
            b(c.expires),
            c.expire_time,
            escape_newlines(&c.author),
            escape_newlines(&c.text)
        );
    }
    for d in w.downtimes.values() {
        let (kind, ident) = match d.target {
            Target::Host(h) => ("hostdowntime", format!("host_name={}", w.host(h).cfg.name)),
            Target::Service(s) => {
                let svc = w.service(s);
                (
                    "servicedowntime",
                    format!("host_name={}\nservice_description={}", w.host(svc.host).cfg.name, svc.cfg.description),
                )
            }
        };
        let _ = writeln!(
            out,
            "{kind} {{\n{ident}\ndowntime_id={}\nentry_time={}\nstart_time={}\nend_time={}\ntriggered_by={}\nfixed={}\nduration={}\nauthor={}\ncomment={}\nx_corax_in_effect={}\nx_corax_flex_start={}\nx_corax_comment_id={}\n}}",
            d.id,
            d.entry_time,
            d.start_time,
            d.end_time,
            d.triggered_by,
            b(d.fixed),
            d.duration,
            escape_newlines(&d.author),
            escape_newlines(&d.comment),
            b(d.is_in_effect),
            d.flex_downtime_start,
            d.comment_id
        );
    }
    out
}

/// Write atomically (temp file + rename).
pub fn save(path: &Path, content: &str) -> std::io::Result<()> {
    let tmp = path.with_extension("tmp-corax");
    std::fs::write(&tmp, content)?;
    std::fs::rename(&tmp, path)
}

#[derive(Debug, Default, PartialEq, Eq)]
pub struct RestoreStats {
    pub hosts: usize,
    pub services: usize,
    pub comments: usize,
    pub downtimes: usize,
    pub skipped: usize,
}

struct Block<'a> {
    kind: &'a str,
    kv: Vec<(&'a str, &'a str)>,
}

impl<'a> Block<'a> {
    fn get(&self, k: &str) -> Option<&'a str> {
        self.kv.iter().rev().find(|(key, _)| *key == k).map(|(_, v)| *v)
    }
    fn i(&self, k: &str) -> Option<i64> {
        self.get(k).and_then(|v| v.trim().parse().ok())
    }
    fn f(&self, k: &str) -> Option<f64> {
        self.get(k).and_then(|v| v.trim().parse().ok())
    }
    fn flag(&self, k: &str) -> Option<bool> {
        self.i(k).map(|v| v != 0)
    }
}

fn blocks(text: &str) -> Vec<Block<'_>> {
    let mut out = Vec::new();
    let mut cur: Option<Block<'_>> = None;
    for line in text.lines() {
        let line = line.trim_end();
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        if let Some(kind) = line.strip_suffix(" {") {
            cur = Some(Block { kind: kind.trim(), kv: Vec::new() });
        } else if line.trim() == "}" {
            out.extend(cur.take());
        } else if let (Some(b), Some((k, v))) = (cur.as_mut(), line.split_once('=')) {
            b.kv.push((k.trim(), v));
        }
    }
    out
}

fn restore_state(st: &mut CheckState, b: &Block<'_>, is_host: bool, use_retained_scheduling: bool) {
    // Status information
    if let Some(v) = b.flag("has_been_checked") {
        st.has_been_checked = v;
    }
    st.execution_time = b.f("check_execution_time").unwrap_or(0.0);
    st.latency = b.f("check_latency").unwrap_or(0.0);
    st.check_type = if b.i("check_type") == Some(1) { CheckType::Passive } else { CheckType::Active };
    st.current_state = b.i("current_state").unwrap_or(0).clamp(0, 3) as u8;
    st.last_state = b.i("last_state").unwrap_or(0).clamp(0, 3) as u8;
    st.last_hard_state = b.i("last_hard_state").unwrap_or(0).clamp(0, 3) as u8;
    st.last_event_id = b.i("last_event_id").unwrap_or(0) as u64;
    st.current_event_id = b.i("current_event_id").unwrap_or(0) as u64;
    st.current_problem_id = b.i("current_problem_id").unwrap_or(0) as u64;
    st.last_problem_id = b.i("last_problem_id").unwrap_or(0) as u64;
    st.plugin_output = unescape_newlines(b.get("plugin_output").unwrap_or(""));
    st.long_plugin_output = unescape_newlines(b.get("long_plugin_output").unwrap_or(""));
    st.perf_data = unescape_newlines(b.get("performance_data").unwrap_or(""));
    st.last_check = b.i("last_check").unwrap_or(0);
    if use_retained_scheduling {
        st.next_check = b.i("next_check").unwrap_or(0);
    }
    st.current_attempt = b.i("current_attempt").unwrap_or(1).max(1) as u32;
    st.state_type = if b.i("state_type") == Some(0) { StateType::Soft } else { StateType::Hard };
    st.last_state_change = b.i("last_state_change").unwrap_or(0);
    st.last_hard_state_change = b.i("last_hard_state_change").unwrap_or(0);
    let names: &[&str] = if is_host {
        &["last_time_up", "last_time_down", "last_time_unreachable"]
    } else {
        &["last_time_ok", "last_time_warning", "last_time_critical", "last_time_unknown"]
    };
    for (i, n) in names.iter().enumerate() {
        st.last_time_in_state[i] = b.i(n).unwrap_or(0);
    }
    st.last_notification = b.i("last_notification").unwrap_or(0);
    st.current_notification_number = b.i("current_notification_number").unwrap_or(0) as u32;
    st.next_notification = b.i("x_corax_next_notification").unwrap_or(0);
    st.no_more_notifications = b.flag("x_corax_no_more_notifications").unwrap_or(false);
    st.acknowledged = b.flag("problem_has_been_acknowledged").unwrap_or(false) && st.current_state != 0;
    st.acknowledgement_type = if st.acknowledged { b.i("acknowledgement_type").unwrap_or(1) as u8 } else { 0 };
    st.acknowledgement_expire_time = if st.acknowledged { b.i("x_corax_ack_expire").unwrap_or(0) } else { 0 };
    st.is_flapping = b.flag("is_flapping").unwrap_or(false);
    st.percent_state_change = b.f("percent_state_change").unwrap_or(0.0);
    if let Some(hist) = b.get("state_history") {
        let vals: Vec<u8> = hist.split(',').filter_map(|v| v.trim().parse().ok()).take(FLAP_HISTORY).collect();
        st.state_history = [0; FLAP_HISTORY];
        for (i, v) in vals.iter().enumerate() {
            st.state_history[i] = *v;
        }
        st.state_history_len = vals.len();
        st.state_history_index = vals.len() % FLAP_HISTORY;
    }

    // Non-status information is only restored if it was changed at runtime
    // (Nagios ≥ 3.0 semantics, so configuration changes take effect).
    let modattrs = b.i("modified_attributes").unwrap_or(0) as u32;
    st.modified_attributes = modattrs;
    let restore = |bit: u32, key: &str, field: &mut bool| {
        if modattrs & bit != 0 {
            if let Some(v) = b.flag(key) {
                *field = v;
            }
        }
    };
    restore(modattr::NOTIFICATIONS_ENABLED, "notifications_enabled", &mut st.notifications_enabled);
    restore(modattr::ACTIVE_CHECKS_ENABLED, "active_checks_enabled", &mut st.active_checks_enabled);
    restore(modattr::PASSIVE_CHECKS_ENABLED, "passive_checks_enabled", &mut st.passive_checks_enabled);
    restore(modattr::EVENT_HANDLER_ENABLED, "event_handler_enabled", &mut st.event_handler_enabled);
    restore(modattr::FLAP_DETECTION_ENABLED, "flap_detection_enabled", &mut st.flap_detection_enabled);
    restore(modattr::PERFORMANCE_DATA_ENABLED, "process_performance_data", &mut st.process_performance_data);
    let obsess_key = if is_host { "obsess_over_host" } else { "obsess_over_service" };
    restore(modattr::OBSESSIVE_HANDLER_ENABLED, obsess_key, &mut st.obsess);
}

/// Restore retained state into a freshly built world.
pub fn restore(w: &mut World, text: &str) -> RestoreStats {
    let mut stats = RestoreStats::default();
    let use_program = w.settings.use_retained_program_state;
    let use_sched = w.settings.use_retained_scheduling_info;
    let mut pending_comments = Vec::new();
    let mut pending_downtimes = Vec::new();
    for b in blocks(text) {
        match b.kind {
            "program" => {
                let p = &mut w.program;
                for (key, field) in [
                    ("next_comment_id", &mut p.next_comment_id),
                    ("next_downtime_id", &mut p.next_downtime_id),
                    ("next_event_id", &mut p.next_event_id),
                    ("next_problem_id", &mut p.next_problem_id),
                    ("next_notification_id", &mut p.next_notification_id),
                ] {
                    if let Some(v) = b.i(key) {
                        *field = (*field).max(v.max(1) as u64);
                    }
                }
                if use_program {
                    let mh = b.i("modified_host_attributes").unwrap_or(0) as u32;
                    let ms = b.i("modified_service_attributes").unwrap_or(0) as u32;
                    p.modified_host_attributes = mh;
                    p.modified_service_attributes = ms;
                    let any = mh | ms;
                    let set = |bit: u32, key: &str, field: &mut bool| {
                        if any & bit != 0 {
                            if let Some(v) = b.flag(key) {
                                *field = v;
                            }
                        }
                    };
                    set(modattr::NOTIFICATIONS_ENABLED, "enable_notifications", &mut p.enable_notifications);
                    set(modattr::ACTIVE_CHECKS_ENABLED, "active_service_checks_enabled", &mut p.execute_service_checks);
                    set(modattr::ACTIVE_CHECKS_ENABLED, "active_host_checks_enabled", &mut p.execute_host_checks);
                    set(
                        modattr::PASSIVE_CHECKS_ENABLED,
                        "passive_service_checks_enabled",
                        &mut p.accept_passive_service_checks,
                    );
                    set(
                        modattr::PASSIVE_CHECKS_ENABLED,
                        "passive_host_checks_enabled",
                        &mut p.accept_passive_host_checks,
                    );
                    set(modattr::EVENT_HANDLER_ENABLED, "enable_event_handlers", &mut p.enable_event_handlers);
                    set(modattr::FLAP_DETECTION_ENABLED, "enable_flap_detection", &mut p.enable_flap_detection);
                    set(modattr::PERFORMANCE_DATA_ENABLED, "process_performance_data", &mut p.process_performance_data);
                }
            }
            "host" => match b.get("host_name").and_then(|n| w.find_host(n)) {
                Some(h) => {
                    restore_state(&mut w.host_mut(h).st, &b, true, use_sched);
                    stats.hosts += 1;
                }
                None => stats.skipped += 1,
            },
            "service" => match (b.get("host_name"), b.get("service_description")) {
                (Some(h), Some(s)) => match w.find_service(h, s) {
                    Some(id) => {
                        restore_state(&mut w.service_mut(id).st, &b, false, use_sched);
                        stats.services += 1;
                    }
                    None => stats.skipped += 1,
                },
                _ => stats.skipped += 1,
            },
            "contact" => {
                if let Some(cid) = b.get("contact_name").and_then(|n| w.contact_by_name.get(n).copied()) {
                    let c = &mut w.contacts[cid.0 as usize];
                    c.last_host_notification = b.i("last_host_notification").unwrap_or(0);
                    c.last_service_notification = b.i("last_service_notification").unwrap_or(0);
                    c.modified_attributes = b.i("modified_attributes").unwrap_or(0) as u32;
                    if c.modified_attributes != 0 {
                        c.host_notifications_enabled =
                            b.flag("host_notifications_enabled").unwrap_or(c.host_notifications_enabled);
                        c.service_notifications_enabled =
                            b.flag("service_notifications_enabled").unwrap_or(c.service_notifications_enabled);
                    }
                }
            }
            "hostcomment" | "servicecomment" => pending_comments.push(b),
            "hostdowntime" | "servicedowntime" => pending_downtimes.push(b),
            _ => {}
        }
    }

    let target_of = |w: &World, b: &Block<'_>| -> Option<Target> {
        let host = b.get("host_name")?;
        match b.get("service_description") {
            Some(s) => w.find_service(host, s).map(Target::Service),
            None => w.find_host(host).map(Target::Host),
        }
    };

    for b in pending_downtimes {
        let Some(t) = target_of(w, &b) else {
            stats.skipped += 1;
            continue;
        };
        let id = b.i("downtime_id").unwrap_or(0) as u64;
        if id == 0 {
            continue;
        }
        let in_effect = b.flag("x_corax_in_effect").unwrap_or(false);
        w.downtimes.insert(
            id,
            Downtime {
                id,
                target: t,
                author: unescape_newlines(b.get("author").unwrap_or("")),
                comment: unescape_newlines(b.get("comment").unwrap_or("")),
                entry_time: b.i("entry_time").unwrap_or(0),
                start_time: b.i("start_time").unwrap_or(0),
                end_time: b.i("end_time").unwrap_or(0),
                fixed: b.flag("fixed").unwrap_or(true),
                duration: b.i("duration").unwrap_or(0),
                triggered_by: b.i("triggered_by").unwrap_or(0) as u64,
                is_in_effect: in_effect,
                flex_downtime_start: b.i("x_corax_flex_start").unwrap_or(0),
                comment_id: b.i("x_corax_comment_id").unwrap_or(0) as u64,
            },
        );
        if in_effect {
            w.state_mut(t).scheduled_downtime_depth += 1;
        }
        w.program.next_downtime_id = w.program.next_downtime_id.max(id + 1);
        stats.downtimes += 1;
    }

    for b in pending_comments {
        let Some(t) = target_of(w, &b) else {
            stats.skipped += 1;
            continue;
        };
        let id = b.i("comment_id").unwrap_or(0) as u64;
        let entry_type = b.i("entry_type").unwrap_or(1) as u8;
        let persistent = b.flag("persistent").unwrap_or(false);
        let keep = match entry_type {
            comment_entry::USER => persistent,
            comment_entry::ACKNOWLEDGEMENT => persistent || w.state(t).acknowledged,
            comment_entry::DOWNTIME => {
                w.downtimes.values().any(|d| d.comment_id == id) || {
                    // Nagios-written retention: no comment id link, keep if a downtime exists
                    w.downtimes.values().any(|d| d.target == t && d.comment_id == 0)
                }
            }
            _ => true,
        };
        if id == 0 || !keep {
            continue;
        }
        w.comments.insert(
            id,
            Comment {
                id,
                target: t,
                entry_type,
                author: unescape_newlines(b.get("author").unwrap_or("")),
                text: unescape_newlines(b.get("comment_data").unwrap_or("")),
                entry_time: b.i("entry_time").unwrap_or(0),
                persistent,
                source: b.i("source").unwrap_or(1) as u8,
                expires: b.flag("expires").unwrap_or(false),
                expire_time: b.i("expire_time").unwrap_or(0),
            },
        );
        w.program.next_comment_id = w.program.next_comment_id.max(id + 1);
        stats.comments += 1;
    }
    stats
}

