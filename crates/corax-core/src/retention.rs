    fn reads_nagios_written_file() {
        let nagios = "info {\ncreated=1\nversion=3.5.1\n}\nprogram {\nmodified_host_attributes=0\nenable_notifications=0\nnext_comment_id=5\n}\nservice {\nhost_name=h1\nservice_description=CPU load\nmodified_attributes=0\ncurrent_state=1\nstate_type=1\nplugin_output=WARN - x\nnotifications_enabled=0\n}\n";
        let mut w = world_from(OBJ);
        restore(&mut w, nagios);
        let s = w.find_service("h1", "CPU load").unwrap();
        assert_eq!(w.service(s).st.current_state, 1);
        // not modified at runtime → configuration value wins
        assert!(w.service(s).st.notifications_enabled);
        assert!(w.program.enable_notifications);
        assert_eq!(w.program.next_comment_id, 5);
    }
